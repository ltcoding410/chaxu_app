CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL, phone VARCHAR(32) UNIQUE,
 password_hash VARCHAR(255), enabled BOOLEAN DEFAULT TRUE NOT NULL
);
CREATE TABLE IF NOT EXISTS roles (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(32) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS user_roles (user_id BIGINT NOT NULL REFERENCES users(id), role_id BIGINT NOT NULL REFERENCES roles(id), PRIMARY KEY(user_id, role_id));
CREATE TABLE IF NOT EXISTS member_accounts (user_id BIGINT PRIMARY KEY REFERENCES users(id), points BIGINT NOT NULL DEFAULT 0);
MERGE INTO roles KEY(id) VALUES (1, 'CUSTOMER'), (2, 'STAFF'), (3, 'ADMIN');
